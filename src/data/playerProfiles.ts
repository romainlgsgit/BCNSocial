// ─── Fiches joueurs (codées en dur) ───────────────────────────────────────────
//
// Ces profils vivent DANS le code (pas dans Firestore) pour ne rien coûter en
// lectures et pour être modifiables en OTA : édite ce fichier puis `npm run ota:prod`
// → les utilisateurs voient la mise à jour au prochain lancement, sans rebuild App Store.
//
// La clé de la map = l'`id` du joueur DANS FIRESTORE (collection `players`, éditée via
// l'écran Admin). Ces ids ne sont PAS ceux de data/mockData.ts : ils sont générés par
// l'admin (type `p_1784...`). Pour resynchroniser après un changement d'effectif, relire
// la collection `players` (lecture publique) et remettre ces clés à jour.
//
// Les stats de carrière (buts, matchs, passes, palmarès) sont indicatives et s'entendent
// « à ce jour ». Chaque champ est optionnel → un champ absent s'affiche « N/A ».

export interface Trophy {
  name: string;
  count: number;
}

export interface PlayerProfile {
  /** = id du doc Firestore `players` */
  id: string;
  fullName?: string;
  birthDate?: string;      // ISO "AAAA-MM-JJ" — l'âge est calculé à l'affichage
  birthPlace?: string;
  height?: number;         // cm
  foot?: 'Gauche' | 'Droit' | 'Ambidextre';
  atBarcaSince?: string;   // année d'intégration à l'équipe première
  previousClubs?: string[];
  careerGoals?: number;    // buts en carrière (clubs + sélection)
  careerAssists?: number;
  careerApps?: number;     // matchs joués en carrière
  clubTrophies?: Trophy[];
  nationalTrophies?: Trophy[];
  awards?: string[];       // distinctions individuelles
  bio?: string;
}

